package dao;

import enums.PlacementStatus;
import model.Student;
import util.DBConnection;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/**
 * Database operations for students.
 * A student is stored in two tables: users (login details) and students (academic details).
 * This class hides that split from the rest of the program.
 * No business rules here: no eligibility checks, no duplicate-email checks.
 */
public class StudentDAO {

    // Shared SELECT used by every read method. Joins both tables so that
    // one row gives us a complete Student object.
    private static final String BASE_SELECT =
            "SELECT u.user_id, u.name, u.email, u.password_hash, u.phone, "
          + "       s.department, s.course, s.graduation_year, s.cgpa, s.backlogs, "
          + "       s.tenth_percentage, s.twelfth_percentage, s.address, s.skills, "
          + "       s.placement_status "
          + "FROM students s "
          + "JOIN users u ON s.student_id = u.user_id ";

    // ---------- CREATE ----------

    /**
     * Inserts a new student into users and students in one transaction.
     * If either insert fails, both are rolled back.
     *
     * @return the new user/student ID generated by the database
     */
    public int addStudent(Student student) throws SQLException {
        try (Connection connection = DBConnection.getConnection()) {
            connection.setAutoCommit(false);
            try {
                int newId = insertUser(connection, student);
                insertStudentDetails(connection, newId, student);
                connection.commit();
                student.setUserId(newId);
                return newId;
            } catch (SQLException e) {
                connection.rollback();
                throw e;
            }
        }
    }

    /** Step 1 of registration: insert the login row and return its generated ID. */
    private int insertUser(Connection connection, Student student) throws SQLException {
        String sql = "INSERT INTO users (name, email, password_hash, phone, role) "
                   + "VALUES (?, ?, ?, ?, 'STUDENT')";
        try (PreparedStatement ps = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, student.getName());
            ps.setString(2, student.getEmail());
            ps.setString(3, student.getPasswordHash());
            ps.setString(4, student.getPhone());
            ps.executeUpdate();

            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getInt(1);
                }
            }
        }
        throw new SQLException("Database did not return an ID for the new student.");
    }

    /** Step 2 of registration: insert the academic row using the same ID. */
    private void insertStudentDetails(Connection connection, int studentId, Student student)
            throws SQLException {
        String sql = "INSERT INTO students (student_id, department, course, graduation_year, cgpa, "
                   + "backlogs, tenth_percentage, twelfth_percentage, address, skills, placement_status) "
                   + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setInt(1, studentId);
            ps.setString(2, student.getDepartment());
            ps.setString(3, student.getCourse());
            ps.setInt(4, student.getGraduationYear());
            ps.setDouble(5, student.getCgpa());
            ps.setInt(6, student.getBacklogs());
            ps.setDouble(7, student.getTenthPercentage());
            ps.setDouble(8, student.getTwelfthPercentage());
            ps.setString(9, student.getAddress());
            ps.setString(10, student.getSkills());
            ps.setString(11, student.getPlacementStatus().name());
            ps.executeUpdate();
        }
    }

    // ---------- READ ----------

    /** Returns the student with this ID, or null if none exists. */
    public Student getStudentById(int studentId) throws SQLException {
        String sql = BASE_SELECT + "WHERE s.student_id = ?";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setInt(1, studentId);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? mapRow(rs) : null;
            }
        }
    }

    /** Returns the student with this email, or null. Used for login and duplicate checks. */
    public Student getStudentByEmail(String email) throws SQLException {
        String sql = BASE_SELECT + "WHERE u.email = ?";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, email);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? mapRow(rs) : null;
            }
        }
    }

    /** Returns every student, ordered by name. */
    public List<Student> getAllStudents() throws SQLException {
        String sql = BASE_SELECT + "ORDER BY u.name";
        return runStudentQuery(sql);
    }

    /**
     * Returns students whose name, email, or department contains the keyword.
     * The same parameter is used three times, so the SQL needs only one value.
     */
    public List<Student> searchStudents(String keyword) throws SQLException {
        String sql = BASE_SELECT
                   + "WHERE u.name LIKE ? OR u.email LIKE ? OR s.department LIKE ? "
                   + "ORDER BY u.name";
        String pattern = "%" + keyword + "%";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, pattern);
            ps.setString(2, pattern);
            ps.setString(3, pattern);
            return readStudents(ps);
        }
    }

    /** Returns students in one department, for the department filter. */
    public List<Student> getStudentsByDepartment(String department) throws SQLException {
        String sql = BASE_SELECT + "WHERE s.department = ? ORDER BY u.name";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, department);
            return readStudents(ps);
        }
    }

    /** Returns students with the given placement status (PLACED or NOT_PLACED). */
    public List<Student> getStudentsByPlacementStatus(PlacementStatus status) throws SQLException {
        String sql = BASE_SELECT + "WHERE s.placement_status = ? ORDER BY u.name";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, status.name());
            return readStudents(ps);
        }
    }

    // ---------- UPDATE ----------

    /**
     * Saves changes to a student's name, phone, and academic details.
     * Updates both tables in one transaction.
     *
     * @return true if the student existed and was updated
     */
    public boolean updateStudent(Student student) throws SQLException {
        try (Connection connection = DBConnection.getConnection()) {
            connection.setAutoCommit(false);
            try {
                int userRows = updateUserBasics(connection, student);
                int studentRows = updateStudentDetails(connection, student);
                connection.commit();
                return userRows > 0 && studentRows > 0;
            } catch (SQLException e) {
                connection.rollback();
                throw e;
            }
        }
    }

    private int updateUserBasics(Connection connection, Student student) throws SQLException {
        String sql = "UPDATE users SET name = ?, email = ?, phone = ? WHERE user_id = ?";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, student.getName());
            ps.setString(2, student.getEmail());
            ps.setString(3, student.getPhone());
            ps.setInt(4, student.getUserId());
            return ps.executeUpdate();
        }
    }

    private int updateStudentDetails(Connection connection, Student student) throws SQLException {
        String sql = "UPDATE students SET department = ?, course = ?, graduation_year = ?, "
                   + "cgpa = ?, backlogs = ?, tenth_percentage = ?, twelfth_percentage = ?, "
                   + "address = ?, skills = ? WHERE student_id = ?";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, student.getDepartment());
            ps.setString(2, student.getCourse());
            ps.setInt(3, student.getGraduationYear());
            ps.setDouble(4, student.getCgpa());
            ps.setInt(5, student.getBacklogs());
            ps.setDouble(6, student.getTenthPercentage());
            ps.setDouble(7, student.getTwelfthPercentage());
            ps.setString(8, student.getAddress());
            ps.setString(9, student.getSkills());
            ps.setInt(10, student.getStudentId());
            return ps.executeUpdate();
        }
    }

    /** Changes only the placement status. Used by the selection flow. */
    public boolean updatePlacementStatus(int studentId, PlacementStatus status) throws SQLException {
        String sql = "UPDATE students SET placement_status = ? WHERE student_id = ?";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, status.name());
            ps.setInt(2, studentId);
            return ps.executeUpdate() > 0;
        }
    }

    /** Replaces the stored password hash. The caller must pass a hash, never plain text. */
    public boolean updatePasswordHash(int userId, String passwordHash) throws SQLException {
        String sql = "UPDATE users SET password_hash = ? WHERE user_id = ?";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setString(1, passwordHash);
            ps.setInt(2, userId);
            return ps.executeUpdate() > 0;
        }
    }

    // ---------- DELETE ----------

    /**
     * Deletes a student. Deleting the users row cascades to students, resumes,
     * and applications, because of the ON DELETE CASCADE rules in the schema.
     */
    public boolean deleteStudent(int studentId) throws SQLException {
        String sql = "DELETE FROM users WHERE user_id = ?";
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setInt(1, studentId);
            return ps.executeUpdate() > 0;
        }
    }

    // ---------- Private helpers ----------

    /** Runs a query with no parameters and collects all rows. */
    private List<Student> runStudentQuery(String sql) throws SQLException {
        try (Connection connection = DBConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(sql)) {
            return readStudents(ps);
        }
    }

    /** Executes a prepared query and converts every row to a Student. */
    private List<Student> readStudents(PreparedStatement ps) throws SQLException {
        List<Student> students = new ArrayList<>();
        try (ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                students.add(mapRow(rs));
            }
        }
        return students;
    }

    /**
     * Converts the current row of a ResultSet into a Student.
     * This is the only place that knows which column holds which field.
     */
    private Student mapRow(ResultSet rs) throws SQLException {
        return new Student(
                rs.getInt("user_id"),
                rs.getString("name"),
                rs.getString("email"),
                rs.getString("password_hash"),
                rs.getString("phone"),
                rs.getString("department"),
                rs.getString("course"),
                rs.getInt("graduation_year"),
                rs.getDouble("cgpa"),
                rs.getInt("backlogs"),
                rs.getDouble("tenth_percentage"),
                rs.getDouble("twelfth_percentage"),
                rs.getString("address"),
                valueOrEmpty(rs.getString("skills")),
                PlacementStatus.valueOf(rs.getString("placement_status")));
    }

    /** The skills column is nullable in the schema, so convert null to "" for safe printing. */
    private String valueOrEmpty(String value) {
        return value == null ? "" : value;
    }
}